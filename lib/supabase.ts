import { createClient } from '@supabase/supabase-js';

// Singleton browser client to avoid multiple instances
let browserClient: ReturnType<typeof createClient> | null = null;

// Server-side client (uses service role key for elevated privileges)
export const createServerClient = () => {
  const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const supabaseServiceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

  if (!supabaseUrl || !supabaseServiceKey) {
    throw new Error('Missing Supabase credentials for server client');
  }

  return createClient(supabaseUrl, supabaseServiceKey, {
    auth: {
      autoRefreshToken: false,
      persistSession: false,
    },
  });
};

// Client-side client (uses public anon key, RLS enforced)
export const createBrowserClientInstance = () => {
  const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const supabaseAnonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

  if (!supabaseUrl || !supabaseAnonKey) {
    throw new Error('Missing Supabase credentials for browser client');
  }

  return createClient(supabaseUrl, supabaseAnonKey, {
    auth: {
      autoRefreshToken: true,
      persistSession: true,
    },
  });
};

// Helper to get server client with error handling
export async function getServerClient() {
  try {
    return createServerClient();
  } catch (error) {
    console.error('Failed to create server client:', error);
    throw error;
  }
}

// Helper to get browser client (singleton pattern - reuses same instance)
export function getBrowserClient() {
  try {
    if (typeof window === 'undefined') {
      throw new Error('getBrowserClient can only be used in browser context');
    }

    if (!browserClient) {
      browserClient = createBrowserClientInstance();
    }

    return browserClient;
  } catch (error) {
    console.error('Failed to create browser client:', error);
    throw error;
  }
}

// Export type for Supabase database
export type Database = any; // Will be generated by Supabase

// Legacy export - use getBrowserClient() in client components, getServerClient() in API routes
export const supabase = undefined;
export const supabaseAdmin = undefined;
